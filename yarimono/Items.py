class ItemCategory(IntEnum):
    TRAINER_LEVEL = auto()
    EVENT_ITEM = auto()
    ULTIMATE_MOVE = auto()
    SCENE_UNLOCK = auto()
    JUNK = auto()
    GOLD = auto()


@dataclass(frozen=True)
class ItemDef:
    code: int  # unique numeric AP item id
    name: str  # AP item name shown to the player
    category: ItemCategory
    classification: ItemClassification

    @property
    def is_progression(self) -> bool:
        return ItemClassification.progression in self.classification

    def effective_classification(self, scenes_randomized: bool) -> ItemClassification:
        """Resolve the classification used at pool-creation time.

        When "randomize_yariman_encyclopedia" is on, non-filler event items become progression.
        """
        if (scenes_randomized
                and self.category == ItemCategory.EVENT_ITEM
                and self.classification != ItemClassification.filler):
            return ItemClassification.progression
        return self.classification


