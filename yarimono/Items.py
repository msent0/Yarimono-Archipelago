"""Yarimono Archipelago items.

Item Categories:

- TRAINER_LEVEL: Each one increases the max trainer level by one.
- EVENT_ITEM: Items that grant access to new scenes.
- ULTIMATE_MOVE: Unlocks access to ultimate moves for each type.
- SCENE_UNLOCK: Unlocks access to scenes in the Yariman Encyclopedia.
- JUNK: Consumables and White Fluff.

"""

